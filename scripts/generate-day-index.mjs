// Generates data/days/index.ts, bundling every day-report JSON into the app so
// no filesystem access is needed at request time (Cloudflare Workers have no
// project filesystem). Run automatically by the dev/build/preview/deploy tasks.
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const DAYS_DIR = path.join(process.cwd(), "data", "days");
const OUT_FILE = path.join(DAYS_DIR, "index.ts");

const files = (await readdir(DAYS_DIR))
  .filter((f) => f.endsWith(".json"))
  .sort();

const names = files.map((f, i) => `day${String(i).padStart(3, "0")}`);
const imports = files.map((f, i) => `import ${names[i]} from "./${f}";`);
const entries = files.map((f, i) => `  { file: "${f}", data: ${names[i]} },`);

const out = `// AUTO-GENERATED by scripts/generate-day-index.mjs — do not edit by hand.
// Regenerated automatically on dev/build/preview/deploy.

${imports.join("\n")}

export interface RawDayEntry {
  file: string;
  data: unknown;
}

/** Every day report in data/days, sorted by filename (= chronological). */
export const RAW_DAYS: RawDayEntry[] = [
${entries.join("\n")}
];
`;

await writeFile(OUT_FILE, out);
console.log(`[days:index] bundled ${files.length} day reports -> data/days/index.ts`);
